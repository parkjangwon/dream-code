#!/usr/bin/env node
import { cpSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const result = await build({
  absWorkingDir: root,
  bundle: true,
  entryPoints: ["src/remote-web-app.tsx"],
  format: "iife",
  jsx: "automatic",
  jsxImportSource: "preact",
  logLevel: "silent",
  minify: true,
  platform: "browser",
  target: "es2020",
  write: false,
});

const script = result.outputFiles?.[0]?.text;
if (script === undefined) {
  throw new Error("remote web bundle was not generated");
}

const style = readFileSync(join(root, "src/remote-web.css"), "utf8");
const generated = [
  "/* Generated by scripts/build-remote-web.mjs. Do not edit by hand. */",
  `export const REMOTE_WEB_CSS = ${JSON.stringify(style)};`,
  `export const REMOTE_WEB_JS = ${JSON.stringify(script)};`,
  "",
].join("\n");

writeFileSync(join(root, "src/remote-web-assets.ts"), generated);

mkdirSync(join(root, "dist/src"), { recursive: true });
cpSync(join(root, "src/assets"), join(root, "dist/src/assets"), { recursive: true });
